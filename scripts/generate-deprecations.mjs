#!/usr/bin/env node
/**
 * Generates `projects/gleks/ui/src/lib/shared/deprecations.ts` — the manifest of everything the
 * library currently deprecates, shipped in the public API as `GOG_DEPRECATIONS`.
 *
 * **Why generate it rather than write it.** The docs site's job is to answer "is this still
 * supported, and until when?" on the row a reader is looking at. That answer already exists in
 * the source — in `@deprecated` tags and in theme.css's fallbacks — and every hand-kept copy of
 * it drifts. `GogSelectOption` proves the failure mode: tagged for removal in 21.4.0, still
 * exported through 21.4.4, because the promise lived only in a comment nobody's build read.
 *
 * **What ends up in it.** Both kinds the library deprecates, because a consumer meets both:
 *
 *   - TypeScript symbols, parsed from their `@deprecated` tags. As of 21.5.0 there are none —
 *     iteration 3 removed all sixteen — so this half is empty on purpose, and the manifest says
 *     so rather than pretending the file is broken.
 *   - CSS custom properties: the three abbreviated prefixes, expanded against the stylesheets
 *     that still resolve them. That is where 21.5.0's deprecations actually live.
 *
 * Run `npm run generate:deprecations` after deprecating or removing anything; `--check` runs in
 * CI next to the token generator, so a stale manifest fails the build.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { glob } from 'node:fs/promises';
import * as prettier from 'prettier';

import { collectDeprecatedTokens, parseTag, readContext, readTag } from './deprecations.mjs';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const uiSrc = path.join(rootDir, 'projects/gleks/ui/src');
const manifestPath = path.join(uiSrc, 'lib/shared/deprecations.ts');

/** Deprecated public symbols, from the `@deprecated` tags in the library's own source. */
function collectSymbols(files) {
  const entries = [];

  for (const file of files) {
    const lines = readFileSync(file, 'utf8').split(/\r?\n/);
    for (let i = 0; i < lines.length; i++) {
      if (!lines[i].includes('@deprecated')) continue;

      const parsed = parseTag(readTag(lines, i));
      if (!parsed.ok) continue; // check-deprecations.mjs is what fails the build on a bad tag

      // The declaration the tag sits on, reduced to its name: `readonly iconTemplate = input…`
      // becomes `iconTemplate`, which is what a docs page has to match a row against.
      const context = readContext(lines, i);
      const name =
        /(?:readonly|const|class|type|interface|function)\s+([A-Za-z_$][\w$]*)/.exec(
          context,
        )?.[1] ??
        /^([A-Za-z_$][\w$]*)/.exec(context)?.[1] ??
        context;

      entries.push({
        kind: 'symbol',
        name,
        replacement: parsed.tag.replacement,
        since: parsed.tag.since,
        sinceDate: parsed.tag.sinceDate,
        removedIn: parsed.tag.removedIn,
      });
    }
  }

  return entries.sort((a, b) => a.name.localeCompare(b.name));
}

function renderManifest(entries) {
  const rows = entries
    .map(
      (entry) => `  {
    kind: '${entry.kind}',
    name: '${entry.name.replace(/'/g, "\\'")}',
    replacement: '${entry.replacement.replace(/'/g, "\\'")}',
    since: '${entry.since}',
    sinceDate: '${entry.sinceDate}',
    removedIn: '${entry.removedIn}',
  },`,
    )
    .join('\n');

  const symbols = entries.filter((entry) => entry.kind === 'symbol').length;
  const tokens = entries.length - symbols;

  return `// GENERATED by scripts/generate-deprecations.mjs — do not edit by hand.
// Run \`npm run generate:deprecations\`; \`npm run check:deprecations\` fails on a stale copy.

/** What kind of thing a deprecation is about: an exported symbol, or a CSS custom property. */
export type GogDeprecationKind = 'symbol' | 'token';

/** One deprecated part of the public API, with the version that removes it. */
export interface GogDeprecation {
  kind: GogDeprecationKind;
  /** The deprecated name — an export, an input, or a \`--gog-*\` custom property. */
  name: string;
  /** What to use instead. */
  replacement: string;
  /** The version that deprecated it, and the day it was announced. */
  since: string;
  sinceDate: string;
  /** The version that removes it. Until then, the deprecated name still works. */
  removedIn: string;
}

/**
 * Everything \`@guildofgleks/ui\` currently deprecates: ${symbols} symbol(s) and ${tokens} token(s).
 *
 * Generated from the library's own source — \`@deprecated\` tags for symbols, and the stylesheets
 * themselves for tokens — so it cannot drift from what actually still resolves. Meant for tooling
 * that has to answer "is this still supported, and until when?": a docs site marking an API row,
 * an editor plugin, a codemod.
 *
 * An empty \`symbol\` half means exactly what it says: nothing in the TypeScript API is deprecated
 * right now.
 */
export const GOG_DEPRECATIONS: readonly GogDeprecation[] = [
${rows}
];
`;
}

const sameContent = (a, b) => a.replace(/\r\n/g, '\n') === b.replace(/\r\n/g, '\n');

/** Writes using the line endings the file already has, so no EOL-only diff appears. */
function writeMatchingEol(filepath, next) {
  let crlf = false;
  try {
    crlf = readFileSync(filepath, 'utf8').includes('\r\n');
  } catch {
    crlf = false;
  }
  writeFileSync(filepath, crlf ? next.replace(/\r?\n/g, '\r\n') : next, 'utf8');
}

export async function buildManifest() {
  const tsFiles = [];
  for await (const entry of glob('**/*.ts', { cwd: uiSrc, withFileTypes: true })) {
    if (entry.isFile() && !entry.name.endsWith('.spec.ts')) {
      tsFiles.push(path.join(entry.parentPath ?? entry.path, entry.name));
    }
  }
  tsFiles.sort();

  const cssSources = [];
  for await (const entry of glob('*.css', {
    cwd: path.join(uiSrc, 'styles'),
    withFileTypes: true,
  })) {
    if (entry.isFile()) {
      cssSources.push(readFileSync(path.join(entry.parentPath ?? entry.path, entry.name), 'utf8'));
    }
  }

  const entries = [...collectSymbols(tsFiles), ...collectDeprecatedTokens(cssSources)];
  const config = (await prettier.resolveConfig(manifestPath)) ?? {};
  return {
    entries,
    source: await prettier.format(renderManifest(entries), { ...config, filepath: manifestPath }),
  };
}

async function main() {
  const check = process.argv.includes('--check');
  const { entries, source } = await buildManifest();

  let current = '';
  try {
    current = readFileSync(manifestPath, 'utf8');
  } catch {
    current = '';
  }

  if (check) {
    if (!sameContent(current, source)) {
      console.error(
        'The deprecation manifest is out of date:\n  lib/shared/deprecations.ts\n\nRun `npm run generate:deprecations`.',
      );
      process.exit(1);
    }
    console.log('Deprecation manifest is up to date.');
    return;
  }

  writeMatchingEol(manifestPath, source);
  const symbols = entries.filter((entry) => entry.kind === 'symbol').length;
  console.log(
    `Generated the deprecation manifest — ${symbols} symbol(s), ${entries.length - symbols} token(s).`,
  );
}

main();
