#!/usr/bin/env node
/**
 * Turns each example folder under `projects/gleks-ui-lab/src/app/examples/<component>/<name>/`
 * into the source text its documentation card displays.
 *
 * **Why generated rather than typed.** The doc pages used to carry the displayed source as
 * hand-written string arrays, one per tab, sitting several hundred lines away from the demo they
 * described. Nothing checked the two against each other, and they drifted: the collapsible
 * "Custom trigger" card showed a `<div>` trigger in its TS tab — the keyboard-inaccessible
 * pattern its own prose warned against — long after the rendered demo had been fixed. Adding a
 * CSS tab tripled the number of copies. Reading the files the page actually renders removes the
 * copy entirely.
 *
 * Output: `sources.generated.ts` next to the component's example folders. Checked in, so the
 * app builds without a generate step; `--check` fails when it is stale, which is what `build:lab`
 * runs.
 *
 * Usage:
 *   node scripts/generate-example-sources.mjs            # write
 *   node scripts/generate-example-sources.mjs --check    # fail if any output is out of date
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';

const EXAMPLES_ROOT = 'projects/gleks-ui-lab/src/app/examples';
const FILES = [
  ['html', 'example.html'],
  ['ts', 'example.ts'],
  ['css', 'example.css'],
];

const check = process.argv.includes('--check');

/** A missing file is an empty tab, not an error: a `provideGogConfig` example has no template. */
function read(dir, name) {
  const path = join(dir, name);
  return existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n').trimEnd() : '';
}

function dirsIn(path) {
  return readdirSync(path).filter((entry) => statSync(join(path, entry)).isDirectory());
}

/**
 * Emits a TS string literal, picking the quote character Prettier would.
 *
 * Prettier uses whichever quote needs fewer escapes, single on a tie — and example sources are
 * full of single quotes (every `import … from '…'`), so guessing wrong here makes the output
 * fail `format:check` while `check:examples` passes, which is a trap for whoever runs both.
 *
 * Backslashes are escaped first: reversing the order would turn every escape this function adds
 * into a literal backslash of its own.
 */
function literal(source) {
  const singles = (source.match(/'/g) ?? []).length;
  const doubles = (source.match(/"/g) ?? []).length;
  const quote = singles > doubles ? '"' : "'";

  const escaped = source
    .replace(/\\/g, '\\\\')
    .replace(new RegExp(quote, 'g'), `\\${quote}`)
    .replace(/\n/g, '\\n');

  return `${quote}${escaped}${quote}`;
}

/** `scroll-size-auto-hide` → `scrollSizeAutoHide`, the key a doc page reads. */
function camel(name) {
  return name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
}

let stale = 0;
let written = 0;

for (const component of dirsIn(EXAMPLES_ROOT)) {
  const componentDir = join(EXAMPLES_ROOT, component);
  const examples = dirsIn(componentDir);

  const entries = examples.map((name) => {
    const dir = join(componentDir, name);
    const files = FILES.map(([key, file]) => `    ${key}: ${literal(read(dir, file))},`).join('\n');
    return `  ${camel(name)}: {\n${files}\n  },`;
  });

  const output =
    `// GENERATED by scripts/generate-example-sources.mjs from the example folders beside this\n` +
    `// file — do not edit by hand. Run \`npm run generate:examples\` after changing an example.\n` +
    `import type { ExampleSource } from '../../components/shared/example-source';\n\n` +
    `export const ${component.toUpperCase().replace(/-/g, '_')}_EXAMPLES = {\n` +
    `${entries.join('\n')}\n` +
    `} as const satisfies Record<string, ExampleSource>;\n`;

  const target = join(componentDir, 'sources.generated.ts');
  const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';

  if (current === output) continue;

  if (check) {
    console.error(`  out of date: ${target}`);
    stale++;
  } else {
    writeFileSync(target, output, 'utf8');
    written++;
  }
}

if (check) {
  if (stale > 0) {
    console.error(`\n${stale} generated example source file(s) are out of date.`);
    console.error('Run `npm run generate:examples`.');
    process.exit(1);
  }
  console.log('Generated example sources are up to date.');
} else {
  console.log(`Generated example sources — ${written} file(s) written.`);
}
